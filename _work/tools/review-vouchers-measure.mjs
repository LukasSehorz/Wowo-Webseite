import { open, primeReveals, sleep } from './review-lib.mjs';
const device = process.argv[2] || 'desktop';
const { browser, page } = await open('/gutscheine', device);
await primeReveals(page);
await page.evaluate(() => window.scrollTo(0, 0));
await sleep(500);
const r = await page.evaluate(() => {
  const px = (v) => Math.round(parseFloat(v) * 100) / 100;
  const byText = (sel, txt) => [...document.querySelectorAll(sel)].find((e) => (e.getAttribute('aria-label') || e.textContent || '').replace(/\s+/g, ' ').trim().startsWith(txt));
  const type = (el) => { if (!el) return null; const cs = getComputedStyle(el); const b = el.getBoundingClientRect(); return { t: (el.getAttribute('aria-label') || el.textContent).replace(/\s+/g, ' ').trim().slice(0, 30), fs: px(cs.fontSize), lh: px(cs.lineHeight), fw: cs.fontWeight, ls: cs.letterSpacing, w: Math.round(b.width), h: Math.round(b.height), x: Math.round(b.left), maxW: cs.maxWidth }; };
  const box = (el) => { if (!el) return null; const cs = getComputedStyle(el); const b = el.getBoundingClientRect(); return { w: Math.round(b.width), h: Math.round(b.height), x: Math.round(b.left), y: Math.round(b.top + scrollY), r: cs.borderRadius, pad: cs.padding, bg: cs.backgroundColor, border: cs.borderWidth + ' ' + cs.borderColor, pos: cs.position, top: cs.top }; };
  const out = {};
  out.h1 = type(document.querySelector('h1'));
  out.heroLead = type(byText('main p', 'Ein Gutschein umfasst'));
  const panel = [...document.querySelectorAll('main div')].find((d) => getComputedStyle(d).backgroundImage.includes('gradient') && d.getBoundingClientRect().width > 300);
  out.heroPanel = box(panel);
  out.heroPanelRatio = panel ? Math.round(panel.getBoundingClientRect().width / panel.getBoundingClientRect().height * 100) / 100 : null;
  const chip = [...document.querySelectorAll('#ablauf *')].find((e) => e.children.length === 0 && e.textContent.trim() === '01');
  out.stepChip = box(chip?.parentElement.getBoundingClientRect().width < 80 ? chip.parentElement : chip);
  out.stepNumeral = type(chip);
  out.stepTitle = type(byText('#ablauf h3', 'Anzahl festlegen'));
  out.stepsH2 = type(byText('h2', 'In vier Schritten'));
  const row = byText('main *', 'Untersuchung')?.closest('li, div');
  out.specRow = box(row);
  out.specLabel = type(byText('main span, main dt, main p', 'Untersuchung'));
  out.specValue = type(byText('main span, main dd, main p', 'Fußform, Beweglichkeit'));
  const price = [...document.querySelectorAll('main *')].find((e) => e.children.length === 0 && /^119/.test(e.textContent.trim()));
  out.price = type(price);
  let pb = price; while (pb && getComputedStyle(pb).backgroundColor !== 'rgb(15, 32, 52)') pb = pb.parentElement;
  out.priceBox = box(pb);
  out.euOsha = type([...document.querySelectorAll('main *')].find((e) => e.children.length === 0 && e.textContent.trim() === 'EU-OSHA'));
  out.classification = type(byText('main p', 'Ob Einlagen Fehltage'));
  out.configH2 = type(byText('h2', 'Anzahl wählen und anfragen'));
  const form = document.querySelector('#anfrage form');
  out.formCard = box(form?.closest('div[class*="border"]') || form?.parentElement);
  out.summary = box(document.querySelector('#anfrage aside'));
  out.stepper = box(document.querySelector('#anfrage button[aria-label="Anzahl verringern"]')?.parentElement);
  out.quick = box(byText('#anfrage button', '10'));
  out.tierChip = box(byText('#anfrage label', '1 bis 9'));
  const sel = byText('#anfrage label', '25 bis 49');
  out.tierSelected = box(sel);
  out.formatCard = box(byText('#anfrage label', 'Digital als PDF'));
  out.input = box(document.querySelector('#anfrage input[name=company]'));
  out.textarea = box(document.querySelector('#anfrage textarea'));
  out.submit = box(document.querySelector('#anfrage aside button[type=submit]'));
  out.total = type(document.querySelector('#anfrage [data-total]'));
  out.groupNumeral = type([...document.querySelectorAll('#anfrage h3 *')].find((e) => e.textContent.trim() === '01'));
  out.groupTitle = type(byText('#anfrage h3', '01'));
  out.faqH2 = type(byText('h2', 'Häufige Fragen'));
  const faqBtn = document.querySelector('#fragen button[aria-expanded]');
  out.faqCard = box(faqBtn?.closest('div[class*="border"]')?.parentElement?.closest('div[class*="rounded"]') || faqBtn?.closest('div').parentElement.parentElement);
  out.faqQuestion = type(faqBtn?.querySelector('span'));
  out.contactH = type(byText('#fragen h2, #fragen h3', 'Lieber persönlich'));
  out.contactCol = box(byText('#fragen h2, #fragen h3', 'Lieber persönlich')?.parentElement);
  out.faqSection = box(document.querySelector('#fragen'));
  return out;
});
for (const [k, v] of Object.entries(r)) console.log(k.padEnd(14), JSON.stringify(v));
await browser.close();
